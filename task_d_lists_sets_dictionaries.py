
# Task D: Lists, Sets, and Dictionaries

# 1. LIST
# A list stores items in order.
# Duplicates are allowed.

products = ["rice", "sugar", "rice"]
print("List:", products)

# Backend example: items in a shopping cart.


# 2. SET
# A set stores only unique items.

unique_products = set(products)
print("Set:", unique_products)

# Backend example: removing duplicate product names.


# 3. DICTIONARY
# A dictionary stores information using key-value pairs.

customer = {
    "name": "Ravi",
    "city": "Mysore",
    "is_active": True
}

print("Dictionary:", customer)
print("Customer name:", customer["name"])

# Backend example: storing customer details.


# SUMMARY
# List: ordered items; duplicates allowed.
# Set: unique items only.
# Dictionary: stores data as key-value pairs.
